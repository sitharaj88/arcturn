/** Reasoning-level provenance store backing `arcturn blame`. */
export interface ProvenanceStore {
  /**
   * Record a new user prompt. Every evidence and mutation recorded afterwards
   * (until the next `beginTurn`) is attributed to it.
   *
   * @param prompt - The user's prompt. Whitespace is collapsed and the text is
   *   clipped to {@link MAX_PROMPT_CHARS} before storage.
   * @returns The new turn's id.
   */
  beginTurn(prompt: string): Promise<string>;

  /**
   * Record one tool result that informed the current turn.
   *
   * @param toolName - Tool that produced it, e.g. `"read"`.
   * @param subject - Path, URL or command it concerned.
   * @param untrusted - Whether the source is attacker-controlled; see
   *   {@link isUntrustedEvidenceSource}.
   */
  recordEvidence(toolName: string, subject: string, untrusted: boolean): Promise<void>;

  /**
   * Record one file write.
   *
   * @param path - Path written; resolved to absolute before storage.
   * @param before - Content immediately before the write, or `null` when the
   *   file did not exist.
   * @param after - Content immediately after the write.
   */
  recordMutation(path: string, before: string | null, after: string): Promise<void>;

  /** Every recorded turn, oldest first. */
  turns(): Promise<ProvenanceTurnSummary[]>;

  /**
   * Every evidence record, oldest first. Pass `turnId` to filter to one turn.
   *
   * @param turnId - Restrict to evidence gathered during this turn.
   */
  evidence(turnId?: string): Promise<ProvenanceEvidenceRecord[]>;

  /**
   * Attribute each line of `file`'s last recorded state to the turn that wrote
   * it.
   *
   * Replays every recorded mutation for the path in order, carrying each
   * line's attribution across the unchanged regions of successive states, so a
   * line written in an early turn and never touched again keeps that early
   * turn. Lines already present before the first recorded mutation are
   * attributed to nobody (no `turnId`).
   *
   * The result describes the last state this store *recorded*, which is not
   * necessarily what is on disk right now — an edit made outside the agent is,
   * by construction, not attributable.
   *
   * @param file - Path to blame; matched after resolving to absolute.
   * @returns One entry per line, or `[]` when the path has no recorded
   *   mutations (or its history is unrecoverable, e.g. an oversize write).
   */
  blame(file: string): Promise<BlameLine[]>;

  /** Flush every queued write. Safe to call more than once. */
  close(): Promise<void>;
}

/** Options for {@link createProvenanceStore}. */
export interface CreateProvenanceStoreOptions {
  /**
   * Largest file content stored per mutation, in bytes (default 1 MiB).
   * Beyond it the record is kept but its blobs are not, so one generated
   * bundle cannot balloon the store. Blame reports such a file as
   * unattributable rather than guessing.
   */
  readonly maxContentBytes?: number;
}

/** Default for {@link CreateProvenanceStoreOptions.maxContentBytes}. */
export const DEFAULT_MAX_CONTENT_BYTES = 1024 * 1024;

/** Prompts longer than this are clipped before storage. */
export const MAX_PROMPT_CHARS = 200;

const MANIFEST_FILE = "manifest.jsonl";
/**
 * Paths whose CONTENT is never copied into the store.
 *
 * The store keeps full file content so `blame` can attribute lines — which
 * would otherwise make `~/.arcturn/provenance` a durable copy of every secret the
 * agent touched, with no purge. Matching files are still recorded as
 * mutations (you can see that a turn changed `.env`), just without bytes.
 */
const SECRET_PATH_PATTERNS: readonly RegExp[] = [
  /(^|\/)\.env(\.|$)/,
  /(^|\/)\.npmrc$/,
  /(^|\/)id_(rsa|ed25519|ecdsa)$/,
  /\.(pem|key|p12|pfx)$/,
  /(^|\/)credentials$/,
  /(^|\/)\.aws\//,
];

/**
 * Whether a path's content must be withheld from the provenance store.
 *
 * @param path - Absolute or relative path being recorded.
 */
export function isSecretPath(path: string): boolean {
  const normalized = path.split("\\").join("/");
  return SECRET_PATH_PATTERNS.some((pattern) => pattern.test(normalized));
}

const BLOBS_DIR = "blobs";

/** Tools whose calls are mutations rather than evidence. */
export const MUTATION_TOOL_NAMES: readonly string[] = ["write", "edit"];

function isMissing(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    (error as NodeJS.ErrnoException).code === "ENOENT"
  );
}

function tryParseLine(line: string): ProvenanceManifestEntry | undefined {
  try {
    return JSON.parse(line) as ProvenanceManifestEntry;
  } catch {
    return undefined;
  }
}

/**
 * File-backed {@link ProvenanceStore}.
 *
 * Every manifest append and blob write goes through one promise queue — the
 * same discipline `FileCheckpointStore` and `JsonlSessionStore` use — so
 * concurrent `recordMutation()` calls can never interleave into a torn line,
 * and the manifest order always matches the order the calls were made in.
 * Blobs are written to a temp name and renamed, so a crash mid-write can never
 * leave a blob whose content does not match its hash.
 */
class FileProvenanceStore implements ProvenanceStore {
  readonly #dir: string;
  readonly #maxContentBytes: number;
  /** Serializes every manifest append and blob write. */
  #queue: Promise<unknown> = Promise.resolve();
  #currentTurnId: string | undefined;
  #dirReady: Promise<void> | undefined;

  constructor(dir: string, options: CreateProvenanceStoreOptions) {
    this.#dir = dir;
    this.#maxContentBytes = options.maxContentBytes ?? DEFAULT_MAX_CONTENT_BYTES;
  }

  async beginTurn(prompt: string): Promise<string> {
    const id = randomUUID();
    const startedAt = Date.now();
    const text = oneLine(prompt, MAX_PROMPT_CHARS);
    await this.#enqueue(async () => {
      this.#currentTurnId = id;
      await this.#append({
        kind: "turn",
        id,
        prompt: text.length === 0 ? "(empty prompt)" : text,
        startedAt,
      });
    });
    return id;
  }

  async recordEvidence(toolName: string, subject: string, untrusted: boolean): Promise<void> {
    const turnId = await this.#turnId();
    const timestamp = Date.now();
    await this.#enqueue(async () => {
      await this.#append({
        kind: "evidence",
        turnId,
        toolName,
        subject,
        untrusted,
        timestamp,
      });
    });
  }

  async recordMutation(path: string, before: string | null, after: string): Promise<void> {
    // Content for secret-looking paths is never persisted: the store would
    // otherwise become a durable copy of every credential the agent touched,
    // with no purge. The mutation itself is still recorded.
    if (isSecretPath(path)) {
      return this.#recordRedactedMutation(path);
    }
    const turnId = await this.#turnId();
    const absolute = resolve(path);
    const timestamp = Date.now();
    await this.#enqueue(async () => {
      const oversize =
        Buffer.byteLength(after, "utf8") > this.#maxContentBytes ||
        (before !== null && Buffer.byteLength(before, "utf8") > this.#maxContentBytes);
      if (oversize) {
        await this.#append({
          kind: "mutation",
          turnId,
          path: absolute,
          beforeBlob: null,
          afterBlob: null,
          oversize: true,
          timestamp,
        });
        return;
      }
      const beforeBlob = before === null ? null : await this.#putBlob(before);
      const afterBlob = await this.#putBlob(after);
      await this.#append({
        kind: "mutation",
        turnId,
        path: absolute,
        beforeBlob,
        afterBlob,
        timestamp,
      });
    });
  }

  async turns(): Promise<ProvenanceTurnSummary[]> {
    const entries = await this.#readManifest();
    const summaries: ProvenanceTurnSummary[] = [];
    const byId = new Map<string, ProvenanceTurnSummary>();
    for (const entry of entries) {
      if (entry.kind === "turn") {
        const summary: ProvenanceTurnSummary = {
          id: entry.id,
          index: summaries.length + 1,
          prompt: entry.prompt,
          startedAt: entry.startedAt,
          mutationCount: 0,
          evidenceCount: 0,
          untrustedCount: 0,
        };
        summaries.push(summary);
        byId.set(entry.id, summary);
        continue;
      }
      // Attribute by the record's own turnId, not by position: a record whose
      // turn is unknown (a tampered or truncated manifest) is simply dropped
      // from the rollup rather than mis-credited to the preceding turn.
      const summary = byId.get(entry.turnId);
      if (!summary) continue;
      if (entry.kind === "mutation") {
        summary.mutationCount += 1;
      } else {
        summary.evidenceCount += 1;
        if (entry.untrusted) summary.untrustedCount += 1;
      }
    }
    return summaries;
  }

  async evidence(turnId?: string): Promise<ProvenanceEvidenceRecord[]> {
    const entries = await this.#readManifest();
    return entries.filter(
      (entry): entry is ProvenanceEvidenceRecord =>
        entry.kind === "evidence" && (turnId === undefined || entry.turnId === turnId),
    );
  }

  async blame(file: string): Promise<BlameLine[]> {
    const absolute = resolve(file);
    const entries = await this.#readManifest();

    const turns = new Map<string, { prompt: string; index: number }>();
    let index = 0;
    for (const entry of entries) {
      if (entry.kind !== "turn") continue;
      index += 1;
      turns.set(entry.id, { prompt: entry.prompt, index });
    }

    const mutations = entries.filter(
      (entry): entry is ProvenanceMutationRecord =>
        entry.kind === "mutation" && entry.path === absolute,
    );
    if (mutations.length === 0) return [];

    /** Current file state; `undefined` means "unrecoverable, resync needed". */
    let state: AttributedLine[] | undefined;

    for (const mutation of mutations) {
      if (mutation.oversize === true || mutation.afterBlob === null) {
        state = undefined;
        continue;
      }
      const after = await this.#getBlob(mutation.afterBlob);
      if (after === undefined) {
        state = undefined;
        continue;
      }
      let before: string | null = null;
      if (mutation.beforeBlob !== null) {
        const content = await this.#getBlob(mutation.beforeBlob);
        if (content === undefined) {
          // The pre-image blob is gone (pruned, or a partial store): its lines
          // cannot be told apart from the ones this turn wrote, and crediting
          // them all to this turn would be a lie. Give up on the replay.
          state = undefined;
          continue;
        }
        before = content;
      }

      // The recorded pre-image is authoritative. When it disagrees with the
      // state replayed so far — a file deleted and recreated behind our back,
      // a gap in the manifest — resync to it with those lines unattributed,
      // rather than carrying stale attributions forward.
      const recorded = unattributed(before);
      const start = state !== undefined && sameText(state, recorded) ? state : recorded;

      state = applyMutation(start, after.split("\n"), mutation);
    }

    if (state === undefined) return [];

    return state.map((entry, i) => {
      const meta = entry.turnId === undefined ? undefined : turns.get(entry.turnId);
      return {
        line: i + 1,
        text: entry.text,
        ...(entry.turnId === undefined ? {} : { turnId: entry.turnId }),
        ...(meta === undefined ? {} : { prompt: meta.prompt, turnIndex: meta.index }),
        ...(entry.at === undefined ? {} : { at: entry.at }),
      } satisfies BlameLine;
    });
  }

  async close(): Promise<void> {
    await this.#queue.catch(() => undefined);
  }

  /** The active turn, opening an untracked one when nothing began a turn yet. */
  async #turnId(): Promise<string> {
    // Mirrors `FileCheckpointStore.snapshot`: dropping a record because no
    // turn was open would lose provenance forever, so an untracked turn is
    // opened instead and the trail stays complete.
    return this.#currentTurnId ?? (await this.beginTurn("(untracked)"));
  }

  /**
   * Record that a secret-looking path changed, without its content.
   *
   * `blame` will show the file as touched by the turn but cannot attribute
   * lines — the honest trade for not persisting credentials.
   */
  async #recordRedactedMutation(path: string): Promise<void> {
    const turnId = await this.#turnId();
    const absolute = resolve(path);
    const timestamp = Date.now();
    await this.#enqueue(async () => {
      await this.#append({
        kind: "mutation",
        turnId,
        path: absolute,
        beforeBlob: null,
        afterBlob: null,
        oversize: true,
        timestamp,
      });
    });
  }

  /** Store `content` under its sha256 and return the digest. */
  async #putBlob(content: string): Promise<string> {
    const buffer = Buffer.from(content, "utf8");
    const sha = createHash("sha256").update(buffer).digest("hex");
    const path = this.#blobPath(sha);
    try {
      await stat(path);
      return sha; // Already stored under this content hash.
    } catch {
      // Fall through and write it.
    }
    await mkdir(this.#blobsDir(), { recursive: true });
    const tmp = join(this.#blobsDir(), `.tmp-${randomUUID()}`);
    await writeFile(tmp, buffer);
    await rename(tmp, path);
    return sha;
  }

  /** Read a blob, or `undefined` when it is missing (e.g. pruned). */
  async #getBlob(sha: string): Promise<string | undefined> {
    try {
      return await readFile(this.#blobPath(sha), "utf8");
    } catch {
      return undefined;
    }
  }

  async #append(entry: ProvenanceManifestEntry): Promise<void> {
    await this.#ensureDir();
    await writeFile(this.#manifestPath(), `${JSON.stringify(entry)}\n`, { flag: "a" });
  }

  async #readManifest(): Promise<ProvenanceManifestEntry[]> {
    let raw: string;
    try {
      raw = await readFile(this.#manifestPath(), "utf8");
    } catch (error) {
      if (isMissing(error)) return [];
      throw error;
    }
    const entries: ProvenanceManifestEntry[] = [];
    for (const line of raw.split("\n")) {
      if (line.trim().length === 0) continue;
      const parsed = tryParseLine(line);
      if (parsed !== undefined) entries.push(parsed);
    }
    return entries;
  }

  #manifestPath(): string {
    return join(this.#dir, MANIFEST_FILE);
  }

  #blobsDir(): string {
    return join(this.#dir, BLOBS_DIR);
  }

  #blobPath(sha: string): string {
    // A manifest is data, not trust. Without this an `afterBlob` of
    // "../../../id_rsa" would make `arcturn blame` an arbitrary-file-read
    // primitive that prints the file as the blamed content.
    if (!/^[0-9a-f]{64}$/.test(sha)) {
      throw new Error(`provenance: blob id is not a sha256 digest: ${JSON.stringify(sha)}`);
    }
    return join(this.#blobsDir(), sha);
  }

  async #ensureDir(): Promise<void> {
    this.#dirReady ??= mkdir(this.#dir, { recursive: true }).then(() => undefined);
    await this.#dirReady;
  }

  /** Chain `fn` onto the write queue so it never overlaps another queued op. */
  #enqueue<T>(fn: () => Promise<T>): Promise<T> {
    const result = this.#queue.catch(() => undefined).then(fn);
    this.#queue = result.catch(() => undefined);
    return result;
  }
}

/** A line plus the turn that introduced it, used while replaying a file. */
interface AttributedLine {
  text: string;
  turnId?: string;
  at?: number;
}

/** Split `text` into lines nobody is credited for. `null` means "no file". */
function unattributed(text: string | null): AttributedLine[] {
  if (text === null) return [];
  return text.split("\n").map((line) => ({ text: line }));
}

/** Whether two states hold exactly the same lines (length included). */
function sameText(a: readonly AttributedLine[], b: readonly AttributedLine[]): boolean {
  if (a.length !== b.length) return false;
  return a.every((line, i) => line.text === b[i]?.text);
}

/** Diff `state` against `afterLines`, carrying attribution across equal lines. */
function applyMutation(
  state: readonly AttributedLine[],
  afterLines: readonly string[],
  mutation: ProvenanceMutationRecord,
): AttributedLine[] {
  const ops = diffLineOps(
    state.map((line) => line.text),
    afterLines,
  );
  const next: AttributedLine[] = [];
  for (const op of ops) {
    if (op.type === "equal") {
      // The carry-across that makes blame useful: an untouched line keeps the
      // turn that first wrote it, however many later edits pass over the file.
      next.push(state[op.oldIndex] as AttributedLine);
    } else if (op.type === "add") {
      next.push({
        text: afterLines[op.newIndex] as string,
        turnId: mutation.turnId,
        at: mutation.timestamp,
      });
    }
  }
  return next;
}

/**
 * Create a {@link ProvenanceStore} backed by `dir`.
 *
 * The directory (and its `blobs/` subdirectory) is created lazily on the first
 * write; `dir` should be unique per session, e.g.
 * `~/.arcturn/provenance/<sessionId>`.
 *
 * @param dir - Directory to store the manifest and blobs in.
 * @param options - Content-size cap.
 */
export function createProvenanceStore(
  dir: string,
  options: CreateProvenanceStoreOptions = {},
): ProvenanceStore {
  return new FileProvenanceStore(dir, options);
}

