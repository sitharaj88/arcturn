/**
 * AGENT BLAME — reasoning-level provenance for agent-written code.
 *
 * `git blame` answers "who changed this line". When an agent wrote most of the
 * file, the useful question is *why*: which prompt was the agent answering,
 * which turn produced the line, and what evidence (files it read, pages it
 * fetched, commands it ran) informed that turn. This module records that trail
 * and reconstructs it per line.
 *
 * Storage is a sibling of `checkpoints.ts` and deliberately mirrors its shape —
 * an append-only JSONL manifest plus a content-addressed blob store, every
 * write serialized through one promise queue, the directory created lazily:
 *
 * ```text
 * <dir>/manifest.jsonl   append-only log of turn/evidence/mutation records
 * <dir>/blobs/<sha256>   content-addressed file snapshots
 * ```
 *
 * Each manifest line is one of:
 *
 * - `{ kind: "turn", id, prompt, startedAt }` — a user prompt. Everything
 *   recorded afterwards (until the next turn) is attributed to it.
 * - `{ kind: "evidence", turnId, toolName, subject, untrusted, timestamp }` —
 *   one non-mutating tool result that informed the turn. `untrusted` is true
 *   for the sources `taint.ts` treats as attacker-controlled (`fetch`,
 *   `websearch`, any MCP tool), which is what makes "this line was written
 *   right after a fetched page said X" auditable.
 * - `{ kind: "mutation", turnId, path, beforeBlob, afterBlob, timestamp }` —
 *   one file write, as a pair of content hashes.
 *
 * ## Why content blobs rather than diffs
 *
 * Line attribution has to replay a file's whole history exactly; a stored diff
 * would have to be re-applied and any drift (an edit made outside the agent, a
 * crash between records) would silently corrupt every later line's blame.
 * Content-addressed blobs make replay exact *and* cost about the same as diffs
 * in the common case: mutation N's `after` and mutation N+1's `before` are the
 * same bytes, so they share one blob, and reverting a file to an earlier state
 * costs nothing new. The real cost is one blob per distinct file state — see
 * `INTEGRATION-provenance.md` for the measured growth and a pruning policy.
 * {@link CreateProvenanceStoreOptions.maxContentBytes} caps the damage a single
 * huge file can do.
 *
 * ## What "attribution" means here
 *
 * {@link ProvenanceStore.blame} replays the recorded mutations for a path in
 * order, diffing each recorded state against the next with an LCS, and carries
 * each surviving line's attribution across unchanged regions. A line the agent
 * wrote in turn 3 and never touched again still reads "turn 3" after ten later
 * edits — that carry-across is the whole point. Lines that were already in the
 * file before the agent first touched it are attributed to nobody.
 *
 * This module intentionally touches nothing else in the CLI: it is wired up by
 * the caller. See `INTEGRATION-provenance.md` at the repo root for the exact
 * call sites in `runtime.ts`, `args.ts` and `main.ts`, none of which this file
 * modifies.
 *
 * @packageDocumentation
 */

