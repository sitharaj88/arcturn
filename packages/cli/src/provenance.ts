/** A user prompt; everything recorded afterwards belongs to it. */
export interface ProvenanceTurnRecord {
  kind: "turn";
  /** Unique id, generated by {@link ProvenanceStore.beginTurn}. */
  id: string;
  /** The prompt the agent was answering, whitespace-collapsed and clipped. */
  prompt: string;
  /** Epoch milliseconds the turn began. */
  startedAt: number;
}

/** One tool result that informed a turn. */
export interface ProvenanceEvidenceRecord {
  kind: "evidence";
  /** Turn this evidence was gathered during. */
  turnId: string;
  /** Tool that produced it, e.g. `"read"`, `"fetch"`. */
  toolName: string;
  /** What it was about — a path, a URL, a command; `""` when unknown. */
  subject: string;
  /**
   * True when the content came from a source `taint.ts` treats as
   * attacker-controlled (`fetch`, `websearch`, any MCP tool). Rendered
   * distinctly by {@link formatBlame}: a line written under the influence of
   * untrusted evidence is the security-relevant case.
   */
  untrusted: boolean;
  timestamp: number;
}

/** One file write, as a pair of content hashes. */
export interface ProvenanceMutationRecord {
  kind: "mutation";
  /** Turn during which the file was written. */
  turnId: string;
  /** Absolute path written. */
  path: string;
  /** sha256 of the content just before the write, or `null` if it did not exist. */
  beforeBlob: string | null;
  /** sha256 of the content just after the write, or `null` when unrecorded. */
  afterBlob: string | null;
  /**
   * Present and `true` when the content exceeded
   * {@link CreateProvenanceStoreOptions.maxContentBytes} and was therefore not
   * stored. Blame cannot replay across such a mutation and says so.
   */
  oversize?: true;
  timestamp: number;
}

/** One line of the provenance manifest. */
export type ProvenanceManifestEntry =
  | ProvenanceTurnRecord
  | ProvenanceEvidenceRecord
  | ProvenanceMutationRecord;

/** Per-turn rollup returned by {@link ProvenanceStore.turns}. */
export interface ProvenanceTurnSummary {
  /** The turn's id. */
  id: string;
  /** 1-based position in the session, in manifest order. */
  index: number;
  /** The prompt the agent was answering. */
  prompt: string;
  startedAt: number;
  /** Mutations recorded during the turn. */
  mutationCount: number;
  /** Evidence records gathered during the turn. */
  evidenceCount: number;
  /** How many of those came from an untrusted source. */
  untrustedCount: number;
}

