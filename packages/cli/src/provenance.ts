/** One line of a file, with the turn that wrote it (if any). */
export interface BlameLine {
  /** 1-based line number in the file's last recorded state. */
  line: number;
  /** The line's text, without its terminator. */
  text: string;
  /** Turn that introduced this exact line; absent for pre-existing lines. */
  turnId?: string;
  /** The prompt that turn was answering; absent for pre-existing lines. */
  prompt?: string;
  /** Epoch milliseconds the line was written; absent for pre-existing lines. */
  at?: number;
  /** 1-based session position of {@link BlameLine.turnId}, for display. */
  turnIndex?: number;
}

