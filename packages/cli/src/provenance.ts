/** One step of a line-level diff, carrying the indices rather than the text. */
export type LineOp =
  | { type: "equal"; oldIndex: number; newIndex: number }
  | { type: "del"; oldIndex: number }
  | { type: "add"; newIndex: number };

/** Cells above this are treated as "too large" for the O(n*m) LCS table. */
const MAX_LCS_CELLS = 4_000_000;

/**
 * Line-level LCS diff, reporting indices instead of text.
 *
 * `packages/tools/src/diff.ts` has the same DP core but only exports
 * {@link createUnifiedDiff}, which returns *formatted* text with three lines of
 * context — attribution needs every line's fate, including the untouched ones
 * a unified diff omits, so the walk is reimplemented here rather than parsed
 * back out of a rendered diff.
 *
 * Above {@link MAX_LCS_CELLS} cells it degrades to "everything replaced",
 * exactly as `diff.ts` does: blame then credits the whole file to the writing
 * turn, which is coarse but never wrong about who touched it.
 *
 * @param oldLines - Lines before the change.
 * @param newLines - Lines after the change.
 * @returns Ops in file order; `equal` carries both indices.
 */
export function diffLineOps(oldLines: readonly string[], newLines: readonly string[]): LineOp[] {
  const n = oldLines.length;
  const m = newLines.length;
  const ops: LineOp[] = [];

  if (n * m > MAX_LCS_CELLS) {
    for (let i = 0; i < n; i++) ops.push({ type: "del", oldIndex: i });
    for (let j = 0; j < m; j++) ops.push({ type: "add", newIndex: j });
    return ops;
  }

  // dp[i][j] = length of the LCS of oldLines[i..] and newLines[j..]
  const dp: Uint32Array[] = [];
  for (let i = 0; i <= n; i++) dp.push(new Uint32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    const dpi = dp[i] as Uint32Array;
    const dpi1 = dp[i + 1] as Uint32Array;
    const oldLine = oldLines[i] as string;
    for (let j = m - 1; j >= 0; j--) {
      dpi[j] =
        oldLine === newLines[j]
          ? (dpi1[j + 1] as number) + 1
          : Math.max(dpi1[j] as number, dpi[j + 1] as number);
    }
  }

  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (oldLines[i] === newLines[j]) {
      ops.push({ type: "equal", oldIndex: i, newIndex: j });
      i++;
      j++;
    } else if ((dp[i + 1] as Uint32Array)[j]! >= (dp[i] as Uint32Array)[j + 1]!) {
      ops.push({ type: "del", oldIndex: i });
      i++;
    } else {
      ops.push({ type: "add", newIndex: j });
      j++;
    }
  }
  while (i < n) ops.push({ type: "del", oldIndex: i++ });
  while (j < m) ops.push({ type: "add", newIndex: j++ });
  return ops;
}

