/**
 * Whether a tool's output is attacker-controlled.
 *
 * Reuses `taint.ts`'s source lists verbatim (`fetch`, `websearch`, and any
 * tool whose name starts with `mcp`) so "untrusted" means exactly the same
 * thing in the provenance trail as it does to the taint tracker.
 *
 * @param toolName - Tool that produced the result.
 */
export function isUntrustedEvidenceSource(toolName: string): boolean {
  if (DEFAULT_TAINT_SOURCES.includes(toolName)) return true;
  const lower = toolName.toLowerCase();
  return DEFAULT_TAINT_SOURCE_PREFIXES.some(
    (prefix) => prefix.length > 0 && lower.startsWith(prefix.toLowerCase()),
  );
}

/** Reads a file's current content; `null` when it does not exist. */
export type ProvenanceFileReader = (path: string) => Promise<string | null>;

/**
 * An {@link AgentEventListener} that also lets a caller await its in-flight
 * work — the event stream is synchronous but reading the file a tool just
 * wrote is not.
 */
export type ProvenanceObserver = AgentEventListener & {
  /** Resolve once every mutation implied by the events so far is recorded. */
  flush(): Promise<void>;
};

/** Extract the plain text of a user prompt message. */
function promptText(message: Message): string {
  if (message.role !== "user") return "";
  return message.content
    .map((block) => (block.type === "text" ? block.text : ""))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

function detailString(
  details: Record<string, unknown> | undefined,
  key: string,
): string | undefined {
  const value = details?.[key];
  return typeof value === "string" ? value : undefined;
}

/**
 * Rebuild a file's pre-image from its post-image and the unified diff the
 * `edit` tool reported.
 *
 * The diff's hunk headers give the new-file line numbers, so everything
 * outside a hunk is identical in both versions and everything inside one is
 * replayed backwards (` ` and `-` lines belong to the old file, `+` lines do
 * not). Exact, and — unlike reading the file a second time — immune to the
 * race between the tool's write and the observer's read.
 *
 * @param after - The file's content after the edit.
 * @param diff - The unified diff from `EditToolDetails.diff`.
 * @returns The pre-edit content, or `undefined` when the diff is unparseable.
 */
export function reconstructBefore(after: string, diff: string): string | undefined {
  const afterLines = after.split("\n");
  const diffLines = diff.split("\n");
  const out: string[] = [];
  let newIndex = 0;
  let sawHunk = false;
  let inHunk = false;

  for (const line of diffLines) {
    const header = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line);
    if (header) {
      const start = Number(header[1]) - 1;
      if (start < newIndex || start > afterLines.length) return undefined;
      for (let i = newIndex; i < start; i++) out.push(afterLines[i] as string);
      newIndex = start;
      sawHunk = true;
      inHunk = true;
      continue;
    }
    if (!inHunk) continue; // `--- a/x` / `+++ b/x` headers, before any hunk.
    const marker = line[0];
    const text = line.slice(1);
    if (marker === " ") {
      if (afterLines[newIndex] !== text) return undefined;
      out.push(text);
      newIndex += 1;
    } else if (marker === "-") {
      out.push(text);
    } else if (marker === "+") {
      if (afterLines[newIndex] !== text) return undefined;
      newIndex += 1;
    } else {
      return undefined;
    }
  }
  if (!sawHunk) return undefined;
  for (let i = newIndex; i < afterLines.length; i++) out.push(afterLines[i] as string);
  return out.join("\n");
}

/**
 * Build an `AgentEvent` listener that drives a {@link ProvenanceStore}.
 *
 * - `runStart` opens a turn named by the user's prompt.
 * - every successful non-mutating tool call becomes one evidence record,
 *   tagged untrusted per {@link isUntrustedEvidenceSource}.
 * - every successful `write`/`edit` becomes one mutation record. The
 *   post-image comes from `readFile` (the tool has already written it by the
 *   time `toolEnd` fires); the pre-image comes from `WriteToolDetails.created`
 *   (`true` ⇒ the file did not exist) or, for `edit`, from replaying
 *   `EditToolDetails.diff` backwards over the post-image, falling back to the
 *   post-image this observer last recorded for the path.
 *
 * All disk work is chained onto one internal queue, so mutations are recorded
 * in event order even though the listener itself must return synchronously,
 * and a failure anywhere is swallowed: provenance must never break a run.
 *
 * `subagentEvent` is deliberately not unwrapped — mirroring `auditObserver`,
 * the runtime subscribes each sub-agent's own stream, so unwrapping here would
 * record every delegated write twice.
 *
 * @param store - Destination provenance store.
 * @param readFile - Reads a file's current content; `null` when absent.
 * @returns A listener with an extra `flush()` for tests and shutdown.
 */
export function provenanceObserver(
  store: ProvenanceStore,
  readFile: ProvenanceFileReader,
): ProvenanceObserver {
  const pending = new Map<string, { toolName: string; input: Record<string, unknown> }>();
  /** Last post-image this observer recorded, per path — the pre-image fallback. */
  const lastAfter = new Map<string, string>();
  let queue: Promise<unknown> = Promise.resolve();

  const enqueue = (fn: () => Promise<unknown>): void => {
    queue = queue
      .catch(() => undefined)
      .then(fn)
      .catch(() => undefined);
  };

  const observe = (event: AgentEvent): void => {
    switch (event.type) {
      case "runStart": {
        // Queued, not fired directly: the previous turn's mutation may still
        // be reading its file, and opening the next turn ahead of it would
        // credit that turn with work the previous prompt asked for.
        enqueue(() => store.beginTurn(promptText(event.prompt)));
        return;
      }
      case "toolStart": {
        pending.set(event.toolCallId, { toolName: event.toolName, input: event.input });
        return;
      }
      case "toolEnd": {
        const started = pending.get(event.toolCallId);
        pending.delete(event.toolCallId);
        const toolName = started?.toolName ?? event.result.toolName;
        if (event.result.isError) return; // A failed call informed nothing and wrote nothing.

        if (!MUTATION_TOOL_NAMES.includes(toolName)) {
          const subject = started ? defaultSubject(toolName, started.input) : "";
          enqueue(() =>
            store.recordEvidence(toolName, subject, isUntrustedEvidenceSource(toolName)),
          );
          return;
        }

        const details = event.result.details;
        const path = detailString(details, "path");
        if (path === undefined) return;
        const created = details?.created === true;
        const diff = detailString(details, "diff");

        // Start the read NOW, not when the queue drains: `toolEnd` is the last
        // moment the file is known to hold what this call wrote, and a later
        // tool call could otherwise overwrite it before the queue got there —
        // which would silently record the wrong post-image.
        const afterRead = readFile(path).catch(() => null);

        enqueue(async () => {
          const after = await afterRead;
          if (after === null) return; // Written then removed before we looked.
          let before: string | null;
          if (created) {
            // Authoritative, and the only correct answer for a recreate: the
            // file did not exist, so no line predates this turn.
            before = null;
          } else {
            before =
              (diff === undefined ? undefined : reconstructBefore(after, diff)) ??
              lastAfter.get(path) ??
              null;
          }
          lastAfter.set(path, after);
          await store.recordMutation(path, before, after);
        });
        return;
      }
      default:
        return;
    }
  };

  return Object.assign(observe, {
    async flush(): Promise<void> {
      await queue.catch(() => undefined);
      await store.close();
    },
  });
}

