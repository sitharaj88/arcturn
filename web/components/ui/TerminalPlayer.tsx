/**
 * A played arcturn session, not a still of one (DESIGN.md §3.1, §3.9).
 *
 * The point the site has to make is that the permission gate is real, and a
 * transcript that already contains its own outcome cannot make it: the reader
 * has no way to tell an enforced stop from a screenshot of one. So this
 * component types the prompt, streams the tool calls, **stops at the gate**,
 * and hands the decision to the reader. Denying is the branch that proves it —
 * the edit never lands, and the turn ends saying so.
 *
 * Every row is drawn by `<TerminalRow>`, from the same structured vocabulary
 * the stills use, so the moving picture and the mocks beside it cannot drift.
 * The one thing drawn here instead is the gate itself: the CLI's bordered
 * permission dialog, with its three answers as real `<button>` rows. That is
 * the whole interaction, and it belongs in the box the product puts it in —
 * not in a strip of key hints bolted under the window.
 *
 * Nothing here is output arcturn would not print. The transcript was checked
 * line for line against `packages/cli/src/display.ts` (`#runStart`'s blank +
 * `▌` prompt, `#toolStart`'s `● glyph name  subject`, `#toolEndBody`'s
 * `⎿ 84 lines` / `⎿ 2 matches · 34 files searched` and the `#diff` head with
 * its `    13 +` continuation rows), `interactive/dialogs.ts`
 * (`permissionDialog`'s line order and `Allow always: <rule> (project)`),
 * and `interactive/app.ts` (the verbatim denial message, and `✓ 12s ·
 * 1.3k tokens` at `runEnd`). Spend is on the status bar because that is where
 * the product keeps it; the checkpoint is *not* a transcript row, because
 * arcturn snapshots silently — that claim lives in the caption instead.
 */

export interface TerminalPlayerProps {
  /** Window title. Defaults to the session the script depicts. */
  title?: string;
  size?: TerminalSize;
  /** §2.3.4 reserves `--shadow-glow` for the primary CTA and the hero terminal. */
  glow?: boolean;
  className?: string;
}

