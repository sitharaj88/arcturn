/** Options for {@link formatBlame}. */
export interface FormatBlameOptions {
  /** Group by turn instead of printing every line (the `--summary` mode). */
  summary?: boolean;
  /**
   * Evidence records for the session. When given, a footer lists what informed
   * each turn that appears in the output, marking untrusted sources.
   */
  evidence?: readonly ProvenanceEvidenceRecord[];
  /** Maximum characters of a prompt shown per row (default `32`). */
  maxPromptWidth?: number;
  /** Path shown in the summary heading; omitted when absent. */
  path?: string;
}

/** The column shown for a line nobody is credited for. */
const NO_TURN = "-";

/** Suffix marking evidence from an attacker-controlled source. */
const UNTRUSTED_MARK = "[untrusted]";

function padEnd(value: string, width: number): string {
  return value.length >= width ? value : value + " ".repeat(width - value.length);
}

function padStart(value: string, width: number): string {
  return value.length >= width ? value : " ".repeat(width - value.length) + value;
}

function turnLabel(line: BlameLine): string {
  return line.turnIndex === undefined ? NO_TURN : `turn ${line.turnIndex}`;
}

function promptLabel(line: BlameLine, width: number): string {
  return line.prompt === undefined ? NO_TURN : `"${oneLine(line.prompt, width)}"`;
}

/**
 * Build the evidence footer: what informed each turn present in `lines`.
 *
 * Untrusted rows are prefixed with `!` and suffixed with `[untrusted]`, so a
 * reader scanning the footer sees at a glance that a fetched page or an MCP
 * server was in the room when these lines were written.
 */
function evidenceFooter(
  lines: readonly BlameLine[],
  evidence: readonly ProvenanceEvidenceRecord[],
): string[] {
  const shown = new Map<string, { index: number; prompt: string }>();
  for (const line of lines) {
    if (line.turnId === undefined || line.turnIndex === undefined) continue;
    if (!shown.has(line.turnId)) {
      shown.set(line.turnId, { index: line.turnIndex, prompt: line.prompt ?? "" });
    }
  }
  if (shown.size === 0) return [];

  const out: string[] = ["", "Evidence"];
  const ordered = [...shown.entries()].sort((a, b) => a[1].index - b[1].index);
  for (const [turnId, meta] of ordered) {
    const rows = evidence.filter((entry) => entry.turnId === turnId);
    out.push(`  turn ${meta.index}  "${oneLine(meta.prompt, 60)}"`);
    if (rows.length === 0) {
      out.push("    (no evidence recorded)");
      continue;
    }
    for (const row of rows) {
      const subject = row.subject === "" ? "" : `  ${oneLine(row.subject, 80)}`;
      out.push(
        row.untrusted
          ? `  ! ${row.toolName}${subject}  ${UNTRUSTED_MARK}`
          : `    ${row.toolName}${subject}`,
      );
    }
  }

  const untrusted = evidence.filter((entry) => entry.untrusted && shown.has(entry.turnId)).length;
  if (untrusted > 0) {
    out.push("");
    out.push(
      `${untrusted} untrusted source${untrusted === 1 ? "" : "s"} informed the turns above — ` +
        "content from the web or an MCP server is data, not instructions.",
    );
  }
  return out;
}

/**
 * Render blame lines for a terminal.
 *
 * Detail mode prints one row per line —
 * `12  turn 3  "fix the session bug"  const x = 1` — with pre-existing lines
 * showing `-` in both attribution columns. Summary mode replaces the rows with
 * a per-turn tally, newest turn first. Both modes append the evidence footer
 * when {@link FormatBlameOptions.evidence} is supplied.
 *
 * @param lines - Output of {@link ProvenanceStore.blame}.
 * @param options - Mode, evidence, and column widths.
 * @returns Lines to print; join with `"\n"`.
 */
export function formatBlame(
  lines: readonly BlameLine[],
  options: FormatBlameOptions = {},
): string[] {
  const promptWidth = options.maxPromptWidth ?? 32;
  if (lines.length === 0) {
    return ["no provenance recorded for this file"];
  }

  const out: string[] = [];

  if (options.summary === true) {
    if (options.path !== undefined) out.push(options.path);
    const groups = new Map<string, { index: number; prompt: string; count: number }>();
    let unattributedCount = 0;
    for (const line of lines) {
      if (line.turnId === undefined) {
        unattributedCount += 1;
        continue;
      }
      const group = groups.get(line.turnId);
      if (group) {
        group.count += 1;
        continue;
      }
      groups.set(line.turnId, {
        index: line.turnIndex ?? 0,
        prompt: line.prompt ?? "",
        count: 1,
      });
    }
    const ordered = [...groups.values()].sort((a, b) => b.index - a.index);
    const labelWidth = Math.max(
      ...ordered.map((group) => `turn ${group.index}`.length),
      "(pre-existing)".length,
    );
    for (const group of ordered) {
      out.push(
        `${padEnd(`turn ${group.index}`, labelWidth)}  ` +
          `${padEnd(`"${oneLine(group.prompt, promptWidth)}"`, promptWidth + 2)}  ` +
          `${padStart(String(group.count), 5)} line${group.count === 1 ? "" : "s"}`,
      );
    }
    if (unattributedCount > 0) {
      out.push(
        `${padEnd("(pre-existing)", labelWidth)}  ${padEnd("", promptWidth + 2)}  ` +
          `${padStart(String(unattributedCount), 5)} line${unattributedCount === 1 ? "" : "s"}`,
      );
    }
  } else {
    const numberWidth = String(lines.length).length;
    const turnWidth = Math.max(...lines.map((line) => turnLabel(line).length));
    const promptColumn = Math.max(...lines.map((line) => promptLabel(line, promptWidth).length));
    for (const line of lines) {
      out.push(
        `${padStart(String(line.line), numberWidth)}  ` +
          `${padEnd(turnLabel(line), turnWidth)}  ` +
          `${padEnd(promptLabel(line, promptWidth), promptColumn)}  ` +
          line.text,
      );
    }
  }

  if (options.evidence !== undefined) out.push(...evidenceFooter(lines, options.evidence));
  return out;
}
